/**
 * תרגום שגיאות ה-SDK של Anthropic להודעה שאפשר לפעול לפיה.
 * משותף לעוזר ולניתוח מסמכים — בלי זה המשתמש מקבל JSON באנגלית
 * מתוך תגובת הספק במקום לדעת מה לתקן.
 */
export function friendlyAiError(e) {
  const known = {
    401: 'המפתח (ANTHROPIC_API_KEY) לא תקין',
    403: 'למפתח אין הרשאה לדגם הזה',
    404: 'הדגם לא נמצא — ייתכן שהשם השתנה',
    429: 'חריגה ממכסת הקריאות — כדאי לנסות בעוד דקה',
    529: 'השירות עמוס כרגע — כדאי לנסות שוב',
  }[e?.status];
  if (known) return new Error(known);
  if (e?.status >= 500) return new Error('תקלה בצד של הספק — כדאי לנסות שוב');
  // 400 ודומיו: ההודעה של הספק היא המידע היחיד שיש, גם אם היא באנגלית
  return new Error(e?.error?.error?.message || e?.message || 'הקריאה נכשלה');
}
